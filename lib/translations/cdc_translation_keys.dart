/// The shared RGC widgets use CDC G-PSF keys; CDC exposes a different namespace.
String cdcApiKey(String key) {
  const prefix = 'issue_matrix_rgc_decision.rgc.';
  if (key == '${prefix}detail.rgc_fallback') return 'rgc_decision.title';
  return key.startsWith(prefix)
      ? 'rgc_decision.${key.substring(prefix.length)}'
      : key;
}
