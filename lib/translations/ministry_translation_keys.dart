/// Translate explicit web keys used by shared PSWG/ministry widgets.
String ministryApiKey(String key, String? page) {
  final namespace = key.split('.').first;
  final prefix = switch (namespace) {
    'dashboard_plenary' => 'plenary_dashboard',
    'dashboard_working_group' => 'dashboard',
    'progress_report' => 'progress_reports',
    'meeting_requests' when page == 'meeting_calendar' => 'meeting_calendar',
    _ => namespace,
  };
  return '$prefix${key.substring(namespace.length)}';
}
